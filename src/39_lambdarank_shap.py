#!/usr/bin/env python3
"""Step 39: SHAP for the LambdaRank model, on exactly the rows and background of step 17 (first part of W2).

LambdaRank's raw score is a ranking score, not log-odds, so its SHAP values are in its own units: shares
and rank agreement are comparable with the other two models, absolute sizes are not.
Interventional TreeSHAP with the same 200-row background as step 17; additivity is checked on every row.

Outputs: outputs/shap/LAMBDARANK.md, lambdarank_group_importance.csv;
         data/clean/shap/lambdarank_shap.parquet (row level, local only)
Run: .venv/bin/python src/39_lambdarank_shap.py
"""
import importlib.util
import json
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))
from ranker_core import FEATURE_GROUPS, FEATURES, Data

spec = importlib.util.spec_from_file_location("step17", Path(__file__).with_name("17_shap.py"))
s17 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(s17)


def main():
    import lightgbm as lgb
    import shap
    t0 = time.time()
    rng = np.random.default_rng(s17.SEED)                       # same draws as step 17: same rows, same background
    X, meta = s17.explained_rows(Data(), rng)
    bg = X[rng.choice(len(X), size=s17.N_BACKGROUND, replace=False)]
    saved = np.load(s17.LOCAL / "background.npz")["x"]
    assert np.array_equal(bg, saved), "background differs from step 17"
    rk = lgb.Booster(model_file=str(s17.MODELS / "lambdarank_model.txt"))
    raw = rk.predict(X, raw_score=True)
    tree = shap.TreeExplainer(rk, data=shap.maskers.Independent(bg, max_samples=s17.N_BACKGROUND),
                              feature_perturbation="interventional", model_output="raw")
    phi = tree.shap_values(X, check_additivity=False)
    base = float(np.atleast_1d(tree.expected_value)[0])
    resid = np.abs(base + phi.sum(1) - raw)
    print(f"SHAP done for {len(X):,} rows ({time.time() - t0:.0f}s)", flush=True)

    group_of = {f: g for g, fs in FEATURE_GROUPS.items() for f in fs}
    share = pd.Series(np.abs(phi).mean(0) / np.abs(phi).mean(0).sum(), index=FEATURES)
    groups = pd.read_csv(s17.OUT / "group_importance.csv", index_col=0)[["lr_share", "lgbm_share"]]
    groups["lambdarank_share"] = share.groupby(group_of).sum()
    groups.to_csv(s17.OUT / "lambdarank_group_importance.csv")
    old = pd.read_parquet(s17.LOCAL / "candidate_shap.parquet")
    phi_gb = old[[f"lgbm__{f}" for f in FEATURES]].to_numpy()
    rho = s17.spearman_rows(np.abs(phi), np.abs(phi_gb))
    top3 = lambda p: np.argsort(-np.abs(p), axis=1)[:, :3]
    overlap = np.array([len(set(a) & set(b)) for a, b in zip(top3(phi), top3(phi_gb))])
    out = pd.concat([meta, pd.DataFrame({f"lambdarank__{f}": phi[:, j] for j, f in enumerate(FEATURES)}),
                     pd.DataFrame({"raw_lambdarank": raw, "lambdarank_shap_residual": resid})], axis=1)
    out.to_parquet(s17.LOCAL / "lambdarank_shap.parquet", index=False)
    q = {k: float(np.quantile(resid, k)) for k in (0.5, 0.99)}
    summary = dict(rows=len(X), base_value=base, max_additivity_error=float(resid.max()), additivity_quantiles=q,
                   rows_over_1e_3=int((resid > 1e-3).sum()), score_sd=float(raw.std()),
                   raw_correlation_with_lightgbm=float(np.corrcoef(raw, old.raw_lgbm)[0, 1]),
                   raw_correlation_with_lr=float(np.corrcoef(raw, old.raw_lr)[0, 1]),
                   per_candidate_spearman_vs_lightgbm_median=float(np.nanmedian(rho)),
                   top3_overlap_vs_lightgbm={str(k): float((overlap == k).mean()) for k in range(4)})
    (s17.OUT / "lambdarank_summary.json").write_text(json.dumps(summary, indent=2))
    top = share.sort_values(ascending=False).head(10)
    o = summary["top3_overlap_vs_lightgbm"]
    md = ["# SHAP for LambdaRank (two-stage)", "",
          f"Generated by `src/39_lambdarank_shap.py` on the {len(X):,} candidate rows and the {s17.N_BACKGROUND}-row background of "
          "step 17. LambdaRank's raw score is a ranking score, not log-odds: compare shares and orderings with the other "
          "models, not absolute sizes.", "", "## Checks", "",
          f"- Additivity (base + sum = raw score): median error {q[0.5]:.1e}, 99th percentile {q[0.99]:.1e}, max "
          f"{summary['max_additivity_error']:.1e}; {summary['rows_over_1e_3']} rows above 1e-3 (score standard deviation {summary['score_sd']:.2f}).",
          f"- Raw-score correlation with LightGBM {summary['raw_correlation_with_lightgbm']:.3f}, with logistic regression "
          f"{summary['raw_correlation_with_lr']:.3f}.", "",
          "## Share of mean |SHAP| by feature group", "", "| Group | Logistic regression | LightGBM | LambdaRank |", "|---|---|---|---|"]
    md += [f"| {g} | {r.lr_share:.1%} | {r.lgbm_share:.1%} | {r.lambdarank_share:.1%} |" for g, r in groups.iterrows()]
    md += ["", "## LambdaRank's ten strongest features", "", "| Feature | Group | Share |", "|---|---|---|"]
    md += [f"| {f} | {group_of[f]} | {v:.1%} |" for f, v in top.items()]
    md += ["", "## Does it explain candidates like LightGBM?", "",
           f"- Per candidate, Spearman of |SHAP| across features: median {summary['per_candidate_spearman_vs_lightgbm_median']:.3f}.",
           f"- Top-3 features shared per candidate: 3 of 3 {o['3']:.1%}, 2 {o['2']:.1%}, 1 {o['1']:.1%}, 0 {o['0']:.1%}."]
    (s17.OUT / "LAMBDARANK.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    print(f"done in {time.time() - t0:.0f}s")


if __name__ == "__main__":
    main()
