#!/usr/bin/env python3
"""Step 18: deeper SHAP analysis on the step-17 values (same 60,000 candidate rows, same background).

A. Group-level agreement: sum SHAP within the six feature groups. Correlated features within a group
   can trade credit, so agreement at group level shows whether the models differ in substance or only
   in how they split credit among near-duplicates.
B. Dependence: mean SHAP (and 10th-90th percentile) per decile of each key feature, both models; how
   linear LightGBM's effect is (R^2 of a straight-line fit of its SHAP on the feature); and how much of
   its SHAP is NOT a function of the feature itself (standard deviation left after subtracting the mean
   SHAP in 50 quantile bins of the feature), i.e. interaction with other features. Logistic regression
   has no interactions, so its residual measures bin-width noise and serves as the reference.
C. Interactions: LightGBM SHAP interaction values (path-dependent) on 3,000 rows; strongest pairs and
   the share of attribution that is interaction rather than main effect.
D. Chosen vs other candidates: mean group SHAP for restaurants the user went on to like vs the rest.
E. Contrastive misses: for each relevant candidate a model left out of its top 10, the score gap to the
   model's 10th item, split by feature group (valid because SHAP values share one base value, so
   phi(a) - phi(b) sums to f(a) - f(b)). Which group most often explains the miss?
F. Background stability: global importance recomputed with other background samples.
Outputs: outputs/shap/explore/ (CSVs and EXPLORE.md). No user ids leave data/clean.
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))
from common import CLEAN, OUTPUTS
from ranker_core import FEATURE_GROUPS, FEATURES

SEED = 42
OUT = OUTPUTS / "shap" / "explore"
ROWS = CLEAN / "shap" / "candidate_shap.parquet"
MODELS_DIR = OUTPUTS / "rankers_two_stage"
GROUPS = list(FEATURE_GROUPS)
KEY = ["log_distance_km", "cf_all", "log_popularity_3m", "months_since_last_review", "cuisine_affinity",
       "price_gap", "shrunk_rating", "log_user_history"]
NAMES = {"lr": "Logistic regression", "lgbm": "LightGBM"}


def spearman_rows(a, b):
    ra = np.argsort(np.argsort(a, axis=1), axis=1).astype(float)
    rb = np.argsort(np.argsort(b, axis=1), axis=1).astype(float)
    ra -= ra.mean(1, keepdims=True); rb -= rb.mean(1, keepdims=True)
    den = np.sqrt((ra ** 2).sum(1) * (rb ** 2).sum(1))
    return np.where(den > 0, (ra * rb).sum(1) / np.where(den > 0, den, 1), np.nan)


def phi(r, m):
    return r[[f"{m}__{f}" for f in FEATURES]].to_numpy()


def group_phi(r, m):
    return np.column_stack([r[[f"{m}__{f}" for f in FEATURE_GROUPS[g]]].sum(axis=1) for g in GROUPS])


def main():
    rng = np.random.default_rng(SEED)
    OUT.mkdir(parents=True, exist_ok=True)
    r = pd.read_parquet(ROWS)
    r = r[r.lgbm_shap_residual <= 1e-3].reset_index(drop=True)
    X = r[[f"x__{f}" for f in FEATURES]].to_numpy()
    md = ["# SHAP exploration", "", f"Generated by `src/18_shap_explore.py` from {len(r):,} candidate rows "
          f"({r.user_id.nunique()} test users) explained in step 17.", ""]

    # A. group-level agreement
    G = {m: group_phi(r, m) for m in NAMES}
    F = {m: phi(r, m) for m in NAMES}
    rho_g = spearman_rows(np.abs(G["lr"]), np.abs(G["lgbm"]))
    rho_f = spearman_rows(np.abs(F["lr"]), np.abs(F["lgbm"]))
    ga = pd.DataFrame({"group": GROUPS,
                       "sign_agreement": [(np.sign(G["lr"][:, j]) == np.sign(G["lgbm"][:, j])).mean() for j in range(len(GROUPS))],
                       "value_correlation": [np.corrcoef(G["lr"][:, j], G["lgbm"][:, j])[0, 1] for j in range(len(GROUPS))],
                       "lr_share": np.abs(G["lr"]).mean(0) / np.abs(G["lr"]).mean(0).sum(),
                       "lgbm_share": np.abs(G["lgbm"]).mean(0) / np.abs(G["lgbm"]).mean(0).sum()})
    ga.to_csv(OUT / "group_agreement.csv", index=False)
    top_g = lambda p: np.argmax(np.abs(p), axis=1)
    same_top_group = (top_g(G["lr"]) == top_g(G["lgbm"])).mean()
    md += ["## A. Agreement at feature level vs group level", "",
           f"- Per candidate, Spearman of |SHAP|: features median {np.nanmedian(rho_f):.3f}; groups median {np.nanmedian(rho_g):.3f}.",
           f"- Same most important group for a candidate: {same_top_group:.1%}.", "",
           "| Group | Sign agreement | Correlation | LR share | LightGBM share |", "|---|---|---|---|---|"]
    md += [f"| {x.group} | {x.sign_agreement:.1%} | {x.value_correlation:.3f} | {x.lr_share:.1%} | {x.lgbm_share:.1%} |"
           for x in ga.itertuples()]

    # B. dependence
    dep, lin = [], []
    for f in KEY:
        j = FEATURES.index(f)
        x = X[:, j]
        bins = pd.qcut(x, 10, duplicates="drop")
        for m in NAMES:
            v = F[m][:, j]
            g = pd.DataFrame({"x": x, "v": v, "bin": bins}).groupby("bin", observed=True)
            d = g.agg(x_mid=("x", "median"), mean=("v", "mean"), p10=("v", lambda s: s.quantile(0.1)),
                      p90=("v", lambda s: s.quantile(0.9)), n=("v", "size")).reset_index(drop=True)
            dep.append(d.assign(feature=f, model=NAMES[m]))
        if x.std() > 0:
            fine = pd.qcut(x, 50, labels=False, duplicates="drop")

            def resid_sd(v):
                return float((v - pd.Series(v).groupby(fine).transform("mean").to_numpy()).std())
            v = F["lgbm"][:, j]
            lin.append(dict(feature=f, lgbm_linear_r2=np.corrcoef(x, v)[0, 1] ** 2,
                            lgbm_sd=float(v.std()), lgbm_residual_sd=resid_sd(v), lr_residual_sd=resid_sd(F["lr"][:, j])))
    pd.concat(dep).to_csv(OUT / "dependence.csv", index=False)
    lin = pd.DataFrame(lin)
    lin.to_csv(OUT / "nonlinearity.csv", index=False)
    md += ["", "## B. Shape of each feature's effect", "",
           "Linear R²: straight-line fit of LightGBM's SHAP on the feature (1 = linear, like logistic regression). "
           "Residual SD: spread of LightGBM's SHAP that the feature's own value does not explain (interaction with "
           "other features), next to its total SD. Logistic regression has no interactions, so its residual "
           "shows how much comes from bin width alone (large for skewed features such as cf_all and "
           "months_since_last_review); LightGBM interacts where its residual clearly exceeds that reference.", "",
           "| Feature | LightGBM linear R² | LightGBM SD | LightGBM residual SD | LR residual SD |", "|---|---|---|---|---|"]
    md += [f"| {x.feature} | {x.lgbm_linear_r2:.2f} | {x.lgbm_sd:.3f} | {x.lgbm_residual_sd:.3f} | {x.lr_residual_sd:.3f} |"
           for x in lin.itertuples()]

    # C. interactions (LightGBM, path-dependent)
    import lightgbm as lgb
    import shap
    gb = lgb.Booster(model_file=str(MODELS_DIR / "lightgbm_model.txt"))
    sub = rng.choice(len(X), size=3000, replace=False)
    iv = shap.TreeExplainer(gb).shap_interaction_values(X[sub])
    main_abs = np.abs(np.einsum("nii->ni", iv)).mean(0)
    off = np.abs(iv).mean(0)
    np.fill_diagonal(off, 0)
    pairs = [(FEATURES[a], FEATURES[b], 2 * off[a, b]) for a in range(len(FEATURES)) for b in range(a + 1, len(FEATURES))]
    inter = pd.DataFrame(pairs, columns=["feature_a", "feature_b", "mean_abs_interaction"]).sort_values(
        "mean_abs_interaction", ascending=False)
    inter.to_csv(OUT / "interactions.csv", index=False)
    inter_share = off.sum() / (off.sum() + main_abs.sum())
    md += ["", "## C. Interactions LightGBM uses (path-dependent SHAP interaction values, 3,000 rows)", "",
           f"Interaction share of total |attribution|: {inter_share:.1%}.", "",
           "| Pair | Mean \\|interaction\\| |", "|---|---|"]
    md += [f"| {x.feature_a} × {x.feature_b} | {x.mean_abs_interaction:.4f} |" for x in inter.head(10).itertuples()]

    # D. chosen vs other candidates
    rel = r.relevant.to_numpy()
    ch = []
    for m in NAMES:
        for j, g in enumerate(GROUPS):
            ch.append(dict(model=NAMES[m], group=g, chosen=G[m][rel, j].mean(), others=G[m][~rel, j].mean(),
                           difference=G[m][rel, j].mean() - G[m][~rel, j].mean()))
    ch = pd.DataFrame(ch)
    ch.to_csv(OUT / "chosen_vs_others.csv", index=False)
    md += ["", f"## D. What separates restaurants users went on to like ({rel.sum():,} of {len(r):,} candidates)", "",
           "Mean group SHAP, chosen minus other candidates (log-odds).", "", "| Group | LR | LightGBM |", "|---|---|---|"]
    piv = ch.pivot(index="group", columns="model", values="difference").loc[GROUPS]
    md += [f"| {g} | {piv.loc[g, NAMES['lr']]:+.3f} | {piv.loc[g, NAMES['lgbm']]:+.3f} |" for g in GROUPS]

    # E. contrastive misses
    rows_e = []
    for m in NAMES:
        score = r[f"raw_{m}"].to_numpy()
        r["_rank"] = pd.Series(score).groupby(r.user_id).rank(ascending=False, method="first").to_numpy()
        for u, d in r.groupby("user_id", sort=False):
            tenth = d[d._rank == 10]
            missed = d[d.relevant & (d._rank > 10)]
            if tenth.empty or missed.empty:
                continue
            gt = G[m][tenth.index[0]]
            for i in missed.index:
                gap = gt - G[m][i]                       # positive entries push the 10th item above the miss
                rows_e.append(dict(model=NAMES[m], gap=score[tenth.index[0]] - score[i], rank=int(r._rank[i]),
                                   main_group=GROUPS[int(np.argmax(gap))], **{f"gap_{g}": gap[k] for k, g in enumerate(GROUPS)}))
    con = pd.DataFrame(rows_e)
    con.to_csv(OUT / "contrastive_misses.csv", index=False)
    share = con.groupby("model").main_group.value_counts(normalize=True).unstack().reindex(columns=GROUPS).fillna(0)
    mean_gap = con.groupby("model")[[f"gap_{g}" for g in GROUPS]].mean()
    md += ["", "## E. Why a model missed a restaurant the user went on to like", "",
           f"{len(con[con.model == NAMES['lr']]):,} (LR) and {len(con[con.model == NAMES['lgbm']]):,} (LightGBM) relevant candidates "
           "outside the top 10. For each, the score gap to the model's 10th recommendation is split by group; the "
           "group with the largest positive share is the main reason.", "",
           "| Group | LR: main reason | LightGBM: main reason | LR: mean gap | LightGBM: mean gap |", "|---|---|---|---|---|"]
    md += [f"| {g} | {share.loc[NAMES['lr'], g]:.1%} | {share.loc[NAMES['lgbm'], g]:.1%} | "
           f"{mean_gap.loc[NAMES['lr'], 'gap_' + g]:+.3f} | {mean_gap.loc[NAMES['lgbm'], 'gap_' + g]:+.3f} |" for g in GROUPS]

    # F. background stability
    import joblib
    from scipy.stats import spearmanr
    lr = joblib.load(MODELS_DIR / "logistic_pipeline.joblib")
    w = lr[-1].coef_[0] / lr[0].scale_
    base_imp = np.abs(F["lr"]).mean(0)
    stab = []
    for k in range(5):
        bg = X[rng.choice(len(X), size=200, replace=False)]
        imp = np.abs((X - bg.mean(0)) * w).mean(0)
        stab.append(dict(model=NAMES["lr"], background=f"sample {k + 1} (200 rows)",
                         rank_corr=spearmanr(base_imp, imp).statistic, max_share_change=np.abs(imp / imp.sum() - base_imp / base_imp.sum()).max()))
    sub = rng.choice(len(X), size=5000, replace=False)
    base_gb = np.abs(F["lgbm"][sub]).mean(0)
    for k, size in enumerate([50, 100, 200]):
        bg = X[rng.choice(len(X), size=size, replace=False)]
        e = shap.TreeExplainer(gb, data=shap.maskers.Independent(bg, max_samples=size), feature_perturbation="interventional",
                               model_output="raw")
        imp = np.abs(e.shap_values(X[sub], check_additivity=False)).mean(0)
        stab.append(dict(model=NAMES["lgbm"], background=f"new sample ({size} rows), 5,000 explained rows",
                         rank_corr=spearmanr(base_gb, imp).statistic, max_share_change=np.abs(imp / imp.sum() - base_gb / base_gb.sum()).max()))
    stab = pd.DataFrame(stab)
    stab.to_csv(OUT / "background_stability.csv", index=False)
    md += ["", "## F. Stability across background samples", "",
           "| Model | Background | Rank correlation with step 17 | Largest change in a feature's share |", "|---|---|---|---|"]
    md += [f"| {x.model} | {x.background} | {x.rank_corr:.3f} | {x.max_share_change:.1%} |" for x in stab.itertuples()]
    (OUT / "EXPLORE.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
