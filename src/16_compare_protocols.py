#!/usr/bin/env python3
"""Step 16: one table comparing the full-catalog (step 13) and two-stage (step 15) protocols,
plus the spread of two-stage test NDCG@10 across sampling seeds.

Reads outputs/rankers*/test_intervals.csv and outputs/rankers_two_stage/{metrics.csv,seeds/*/metrics.csv}.
Writes outputs/MODEL_COMPARISON.md and outputs/model_comparison.csv (tidy, for figures).
"""
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))
from common import OUTPUTS

ORDER = ["Popularity", "Recent popularity", "Item-CF", "Logistic regression", "LightGBM",
         "LightGBM LambdaRank (supplementary)"]


def main():
    rows = []
    for protocol, folder in [("full catalog", "rankers"), ("two-stage", "rankers_two_stage")]:
        ci = pd.read_csv(OUTPUTS / folder / "test_intervals.csv")
        ci["protocol"] = protocol
        rows.append(ci[ci.model != "Stage 1 candidates"])
    tidy = pd.concat(rows)
    tidy.to_csv(OUTPUTS / "model_comparison.csv", index=False)

    runs = {"42": OUTPUTS / "rankers_two_stage" / "metrics.csv"}
    for p in sorted((OUTPUTS / "rankers_two_stage" / "seeds").glob("seed_*/metrics.csv")):
        runs[p.parent.name.split("_")[1]] = p
    seeds = pd.concat([pd.read_csv(p).assign(seed=k) for k, p in runs.items()])
    seeds = seeds[seeds.period == "test"].pivot_table(index="model", columns="seed", values="NDCG@10")

    md = ["# Model comparison", "", "Generated by `src/16_compare_protocols.py`. Test period 2020-08-01 to "
          "2021-04-30; same users, features, labels and cutoffs in both protocols.", "",
          "## Test NDCG@10 [95% user bootstrap interval]", "", "| Model | Full catalog | Two-stage |", "|---|---|---|"]
    for m in ORDER:
        cells = []
        for protocol in ("full catalog", "two-stage"):
            r = tidy[(tidy.model == m) & (tidy.metric == "ndcg") & (tidy.protocol == protocol)]
            cells.append(f"{r['mean'].iloc[0]:.4f} [{r.lo.iloc[0]:.4f}, {r.hi.iloc[0]:.4f}]" if len(r) else "—")
        md.append(f"| {m} | " + " | ".join(cells) + " |")
    md += ["", "Baselines rank the full catalog in both protocols, so their rows are identical.", "",
           f"## Two-stage test NDCG@10 across sampling seeds ({len(runs)} runs)", "",
           "Seeds change the sampled negatives and the validation users used for model selection.", "",
           "| Model | " + " | ".join(f"seed {k}" for k in seeds.columns) + " | mean | range |",
           "|---|" + "---|" * (len(seeds.columns) + 2)]
    for m in [m for m in ORDER if m in seeds.index]:
        v = seeds.loc[m]
        md.append(f"| {m} | " + " | ".join(f"{x:.4f}" for x in v) + f" | {v.mean():.4f} | {v.max() - v.min():.4f} |")
    (OUTPUTS / "MODEL_COMPARISON.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
