#!/usr/bin/env python3
"""Step 10: audit the processed inputs before cleaning. Reads only; writes outputs/data_audit/.

Every number in AUDIT.md is computed here from data/processed (and, with --raw, the raw review file).
Outputs:
  AUDIT.md                       findings with the numbers behind them
  monthly_reviews.csv            NYC restaurant reviews per month (all users)
  restaurant_activity.csv        per year: restaurants with >=1 review, first-review and last-review counts
  bulk_days.csv                  histogram of reviews per user per local day
  popularity_concentration.csv   share of reviews held by the top x% of restaurants
  user_travel.csv                quantiles of km from each sample user's median visit point
  raw_reviews_by_year.csv        (--raw) all New York reviews per year, and 2021 per month
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))
from common import (BULK_DAY_MIN, LOCAL_TZ, MATCHES, OUTPUTS, RESTAURANTS_NYC, REVIEWS,
                    REVIEWS_NYC, SAMPLE, INSPECTIONS)

OUT = OUTPUTS / "data_audit"
NON_RESTAURANT = re.compile(r"restaurant supply store|bar restaurant furniture store", re.I)


def pct(x):
    return f"{100 * x:.1f}%"


def raw_by_year():
    pat = re.compile(rb'"time": (\d+)')
    proc = subprocess.Popen(["gzip", "-dc", str(REVIEWS)], stdout=subprocess.PIPE, bufsize=1 << 22)
    ts = [int(m.group(1)) for line in proc.stdout if (m := pat.search(line))]
    proc.wait()
    t = pd.to_datetime(pd.Series(ts), unit="ms")
    year = t.dt.year.value_counts().sort_index().rename("reviews").rename_axis("period")
    m21 = t[t.dt.year == 2021].dt.to_period("M").astype(str).value_counts().sort_index()
    m21 = m21.rename("reviews").rename_axis("period")
    df = pd.concat([year.reset_index().astype({"period": str}), m21.reset_index()])
    return df, len(t), t.min(), t.max()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", action="store_true", help="also scan the 2.5 GB raw review file (~3 min)")
    args = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    md = ["# Data audit", "", "Generated by `src/10_data_audit.py` from `data/processed`. "
          "Inputs are not modified.", ""]

    # Restaurants
    R = pd.read_parquet(RESTAURANTS_NYC)
    cats = R.categories.fillna("").str.split("; ").explode()
    bad = R.categories.fillna("").str.contains(NON_RESTAURANT)
    md += ["## Restaurants (`restaurants_nyc.parquet`)", "",
           f"- {len(R):,} restaurants; {cats.nunique()} distinct Google categories.",
           f"- {bad.sum()} carry a non-restaurant category (restaurant supply or furniture store).",
           f"- Primary category is a non-food venue: " + ", ".join(
               f"{k} {n}" for k, n in R.categories.str.split("; ").str[0].value_counts()
               .reindex(["Shopping mall", "Gas station", "Convenience store", "Tourist attraction", "Hotel",
                         "Event venue", "Grocery store", "Food court"]).dropna().astype(int).items()) + ".",
           f"- Price level missing for {pct(R.price_level.isna().mean())}.",
           f"- Permanently closed at the 2021 crawl: {pct(R.permanently_closed_2021.mean())}.",
           f"- Duplicate name + address pairs: {R.duplicated(['name', 'address']).sum()}.",
           f"- Rating, review count, open state and attributes are a single 2021 snapshot: "
           "not usable as features for earlier cutoffs.", ""]

    # Reviews
    r = pd.read_parquet(REVIEWS_NYC, columns=["user_id", "gmap_id", "time_ms", "rating"])
    r["time"] = pd.to_datetime(r.time_ms, unit="ms")
    dup = r.duplicated(["user_id", "gmap_id", "time_ms", "rating"])
    local = r.time.dt.tz_localize("UTC").dt.tz_convert(LOCAL_TZ)
    r["local_date"] = local.dt.date
    monthly = r[r.time >= "2016-01-01"].time.dt.to_period("M").value_counts().sort_index()
    monthly.rename("reviews").rename_axis("month").to_csv(OUT / "monthly_reviews.csv")
    per_day = r[~dup].groupby(["user_id", "local_date"]).size()
    hist = per_day.clip(upper=30).value_counts().sort_index().rename("user_days").rename_axis("reviews_that_day")
    hist.to_csv(OUT / "bulk_days.csv")
    first = r.groupby("gmap_id").time.min().dt.year.value_counts()
    last = r.groupby("gmap_id").time.max().dt.year.value_counts()
    active = r.assign(y=r.time.dt.year).groupby("y").gmap_id.nunique()
    act = pd.DataFrame({"active": active, "first_review": first, "last_review": last}).fillna(0).astype(int)
    act.loc[2014:].rename_axis("year").to_csv(OUT / "restaurant_activity.csv")
    n_item = r[~dup].groupby("gmap_id").size().sort_values(ascending=False)
    share = n_item.cumsum() / n_item.sum()
    conc = pd.DataFrame({"top_share_of_restaurants": [0.01, 0.05, 0.1, 0.2, 0.5],
                         "share_of_reviews": [share.iloc[max(1, int(q * len(n_item))) - 1]
                                              for q in [0.01, 0.05, 0.1, 0.2, 0.5]]})
    conc.to_csv(OUT / "popularity_concentration.csv", index=False)
    feb, apr = monthly.get(pd.Period("2020-02")), monthly.get(pd.Period("2020-04"))
    tail = monthly[monthly.index >= pd.Period("2021-04")]
    md += ["## Reviews (`reviews_nyc.parquet`)", "",
           f"- {len(r):,} reviews, {r.user_id.nunique():,} users, {r.time.min()} to {r.time.max()} (UTC).",
           f"- Rows with no user id or rating: {(r.user_id.isna() | r.rating.isna()).sum():,}.",
           f"- Exact duplicate rows (user, restaurant, time, rating): {dup.sum():,}.",
           f"- Placeholder dates before 2000: {(r.time < '2000-01-01').sum():,}.",
           f"- COVID: {feb:,} reviews in Feb 2020, {apr:,} in Apr 2020.",
           "- Collection tail: " + ", ".join(f"{p} {v:,}" for p, v in tail.items()) + ".",
           f"- User-days with >= {BULK_DAY_MIN} reviews: {(per_day >= BULK_DAY_MIN).sum():,} "
           f"holding {per_day[per_day >= BULK_DAY_MIN].sum():,} reviews; timestamps are posting times.",
           f"- Top 10% of restaurants hold {pct(conc.share_of_reviews[2])} of reviews.",
           f"- Most common hour: {r.time.dt.hour.mode()[0]} UTC = {local.dt.hour.mode()[0]} New York time.", ""]

    # Sample
    s = pd.read_parquet(SAMPLE)
    s_local = s.time.dt.tz_localize("UTC").dt.tz_convert(LOCAL_TZ).dt.date
    day_n = per_day.reindex(pd.MultiIndex.from_arrays([s.user_id, s_local])).to_numpy()
    tr = set(s[s.split == "train"].gmap_id)
    g = s.groupby("user_id").rating.agg(["std", "mean"])
    no_neg = (s.assign(n=s.rating <= 2).groupby("user_id").n.sum() == 0).sum()
    s_bad = s.gmap_id.isin(R.gmap_id[bad])
    md += ["## Sample (`sample_interactions.parquet`)", "",
           f"- {len(s):,} interactions, {s.user_id.nunique():,} users, {s.gmap_id.nunique():,} restaurants.",
           "- Splits: " + "; ".join(f"{k} {v:,} ({s[s.split == k].time.min().date()} to "
                                    f"{s[s.split == k].time.max().date()})"
                                    for k, v in s.split.value_counts().items()) + ".",
           f"- Positive (4-5 stars): {pct((s.rating >= 4).mean())}; users with no 1-2 star review: {no_neg:,}; "
           f"users rating everything 5: {((g['std'] == 0) & (g['mean'] == 5)).sum():,}.",
           f"- On bulk days (>= {BULK_DAY_MIN} reviews that local day): {pct(np.mean(day_n >= BULK_DAY_MIN))}.",
           f"- Test interactions on restaurants unseen in train: "
           f"{pct((~s[s.split == 'test'].gmap_id.isin(tr)).mean())}.",
           f"- Interactions on non-restaurants: {s_bad.sum()}.", ""]

    # Travel
    m = s.merge(R[["gmap_id", "latitude", "longitude"]], on="gmap_id")
    lat0 = m.groupby("user_id").latitude.transform("median")
    lon0 = m.groupby("user_id").longitude.transform("median")
    km = np.hypot((m.latitude - lat0) * 111.0, (m.longitude - lon0) * 111.0 * np.cos(np.radians(40.73)))
    q = km.quantile([0.5, 0.75, 0.9, 0.95, 0.99])
    q.rename("km").rename_axis("quantile").to_csv(OUT / "user_travel.csv")
    md += ["## Travel", "", "Distance from each sample user's median visit point (all splits; "
           "descriptive only, not a feature): " + ", ".join(f"p{int(k * 100)} {v:.1f} km" for k, v in q.items()) + ".", ""]

    # Inspections
    ins = pd.read_csv(INSPECTIONS, usecols=["last_inspection"])
    li = pd.to_datetime(ins.last_inspection, errors="coerce")
    M = pd.read_parquet(MATCHES)
    md += ["## Inspections", "",
           f"- {len(ins):,} records; last inspection {li[li.dt.year > 1900].min().date()} to {li.max().date()}; "
           f"{(li.dt.year == 1900).sum():,} use the 1900-01-01 placeholder (not yet inspected).",
           f"- {pct((li.dt.year >= 2025).mean())} were last inspected in 2025-2026, years after the reviews end: "
           "context and cuisine labels only, never a predictive feature.",
           f"- Matched restaurants: {len(M):,}; DOHMH cuisine labels: {M.cuisine_description.nunique()}.", ""]

    if args.raw:
        df, n, lo, hi = raw_by_year()
        df.to_csv(OUT / "raw_reviews_by_year.csv", index=False)
        md += ["## Raw New York reviews", "", f"- {n:,} reviews, {lo} to {hi} (UTC). "
               "Per year and 2021 per month in `raw_reviews_by_year.csv`.", ""]

    (OUT / "AUDIT.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
